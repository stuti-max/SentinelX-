import React from 'react';
import { Zap, Server, ShieldAlert } from 'lucide-react';

interface TelemetryTagProps {
  type: 'simulated' | 'telemetry' | 'waf-probe';
  className?: string;
  showTooltip?: boolean;
}

export const TelemetryTag: React.FC<TelemetryTagProps> = ({
  type,
  className = '',
}) => {
  if (type === 'simulated') {
    return (
      <span
        title="Demonstration security dataset generated by SentinelX simulation pipeline. Not actual attacks."
        className={`inline-flex items-center gap-1 px-2 py-0.5 rounded text-[10px] font-mono font-semibold tracking-wide border border-[#E4BFBF] bg-[#FDF7F7] text-[#9A5050] ${className}`}
      >
        <Zap className="w-2.5 h-2.5 text-[#D99A9A]" />
        <span>SIMULATED SECURITY DATA</span>
      </span>
    );
  }

  if (type === 'waf-probe') {
    return (
      <span
        title="Synthetic security probe injected for detection testing"
        className={`inline-flex items-center gap-1 px-1.5 py-0.5 rounded text-[9px] font-mono border border-[#E4BFBF] bg-[#FDF7F7] text-[#9A5050] ${className}`}
      >
        <ShieldAlert className="w-2.5 h-2.5 text-[#D99A9A]" />
        <span>SYNTHETIC PROBE</span>
      </span>
    );
  }

  return (
    <span
      title="Live container, pod, and Redis health telemetry from cluster runtime"
      className={`inline-flex items-center gap-1 px-2 py-0.5 rounded text-[10px] font-mono font-semibold tracking-wide border border-[#D8DFE2] bg-[#F4F7F8] text-[#4A5155] ${className}`}
    >
      <Server className="w-2.5 h-2.5 text-[#70777B]" />
      <span>INFRASTRUCTURE TELEMETRY</span>
    </span>
  );
};
